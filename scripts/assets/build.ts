// Optimizes the raw CC0 models into public/models and generates the typed manifest + credits.
// Usage: npm run assets:build   (run assets:fetch first)

import { mkdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { NodeIO } from "@gltf-transform/core";
import { ALL_EXTENSIONS } from "@gltf-transform/extensions";
import { dedup, getBounds, meshopt, prune, resample } from "@gltf-transform/functions";
import { MeshoptDecoder, MeshoptEncoder } from "meshoptimizer";
import { bakePlants } from "./bakePlants.ts";
import { OUT_DIR, rawPath, SOURCES } from "./sources.ts";

/** Animation clips the game uses; everything else is dropped to keep files small. */
/** Clips the game plays; everything else is dropped (big animals ship ~20 clips). */
const ANIMAL_CLIPS = new Set(["Idle", "Idle_Peck", "Idle_Eating", "Eating", "Walk"]);
const FARMER_CLIPS = new Set(["Idle", "Walk", "Run", "Interact", "Wave"]);
const NPC_CLIPS = new Set(["Idle", "Wave"]);
const keepClips = (key: string) =>
  key === "farmer" ? FARMER_CLIPS : key.startsWith("npc_") ? NPC_CLIPS : ANIMAL_CLIPS;

await Promise.all([MeshoptEncoder.ready, MeshoptDecoder.ready]);

const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({
  "meshopt.encoder": MeshoptEncoder,
  "meshopt.decoder": MeshoptDecoder,
});
mkdirSync(OUT_DIR, { recursive: true });
mkdirSync("public/licenses", { recursive: true });

interface Entry {
  url: string;
  tris: number;
  /** Bounding box of the model as authored. */
  min: [number, number, number];
  max: [number, number, number];
  clips: string[];
  bytes: number;
  credit: string;
}

const manifest: Record<string, Entry> = {};

for (const source of SOURCES) {
  const doc = await io.read(rawPath(source));
  const root = doc.getRoot();

  // Clip names arrive as "Armature|Armature|Idle", sometimes twice; keep one short copy of each wanted clip.
  const kept = new Set<string>();
  for (const animation of root.listAnimations()) {
    const name = animation.getName().split("|").at(-1) ?? animation.getName();
    if (!keepClips(source.key).has(name) || kept.has(name)) {
      // Dispose the clip's samplers and channels too, so prune can drop their keyframe data.
      for (const channel of animation.listChannels()) channel.dispose();
      for (const sampler of animation.listSamplers()) sampler.dispose();
      animation.dispose();
      continue;
    }
    animation.setName(name);
    kept.add(name);
  }

  await doc.transform(resample(), dedup(), prune({ keepAttributes: false }));
  // Accessors left without any parent (from dropped clips) are dead weight.
  for (const accessor of root.listAccessors()) {
    if (accessor.listParents().every((p) => p === root)) accessor.dispose();
  }
  // Bounds are measured before compression quantizes the geometry.
  const preScene = root.getDefaultScene() ?? root.listScenes()[0];
  if (!preScene) throw new Error(`${source.key}: no scene`);
  const bounds = getBounds(preScene);
  await doc.transform(meshopt({ encoder: MeshoptEncoder, level: "medium" }));

  let tris = 0;
  for (const mesh of root.listMeshes()) {
    for (const prim of mesh.listPrimitives()) {
      const indices = prim.getIndices();
      tris += Math.floor(
        (indices ? indices.getCount() : (prim.getAttribute("POSITION")?.getCount() ?? 0)) / 3,
      );
    }
  }
  const out = join(OUT_DIR, `${source.key}.glb`);
  await io.write(out, doc);
  const round = (v: number) => Math.round(v * 1000) / 1000;
  manifest[source.key] = {
    url: `/models/${source.key}.glb`,
    tris,
    min: bounds.min.map(round) as [number, number, number],
    max: bounds.max.map(round) as [number, number, number],
    clips: [...kept].sort(),
    bytes: statSync(out).size,
    credit: `"${source.title}" by ${source.author} (${source.licence}) — ${source.page}`,
  };
  console.log(
    `${source.key.padEnd(20)} ${String(tris).padStart(5)} tris  ${((manifest[source.key]?.bytes ?? 0) / 1024).toFixed(0).padStart(5)} KB  clips: ${[...kept].join(", ") || "-"}`,
  );
}

const total = Object.values(manifest).reduce((sum, e) => sum + e.bytes, 0);
console.log(
  `\nTotal ${(total / 1024 / 1024).toFixed(2)} MB in ${Object.keys(manifest).length} models`,
);

const banner = "// GENERATED by scripts/assets/build.ts — do not edit by hand.\n";
writeFileSync(
  "src/game/assets/manifest.ts",
  `${banner}\nexport const MODELS = ${JSON.stringify(manifest, null, 2)} as const;\n\nexport type ModelKey = keyof typeof MODELS;\n`,
);

const plantCredits = await bakePlants(OUT_DIR);

const credits = [
  "# Clover Fields — art credits",
  "",
  "3D models are CC0 1.0 (public domain) unless marked CC-BY 3.0, which requires the credit given here (https://creativecommons.org/licenses/by/3.0/). CC0 credit is given with thanks even though it isn't required.",
  "",
  ...SOURCES.map((s) => `- **${s.key}**: ${manifest[s.key]?.credit ?? ""}`),
  "",
  ...plantCredits,
  "",
  "Soil and a few small decorations are procedural models made for this game.",
  "",
].join("\n");
writeFileSync("public/licenses/CREDITS.md", credits);
